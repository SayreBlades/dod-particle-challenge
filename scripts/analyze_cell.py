#!/usr/bin/env python3
"""Prototype: analyze ONE cell → <cell>.json + <cell>.md.

Produces the per-cell analysis pair described in
`.scratch/plan/reporting-and-analysis.md` §2/§5 for a single cell, using:
  - runs.jsonl   (measured series)
  - hardware.json (cache hierarchy + streaming ceiling)
  - pmc.jsonl    (cycle attribution, if present)
  - assembly     (the cell's rebuilt binary → disassembly of `step`)

The <cell>.json is the structured evidence bundle (deterministic). The <cell>.md
is the narrative, generated by an LLM (z.ai / GLM, OpenAI-compatible) from the
evidence — Tier-2 narrative per plan decision 2.

Usage:
    scripts/analyze_cell.py L1.B1.w1-autovec.w2-opt            # full: json + md
    scripts/analyze_cell.py L1.B1.w1-autovec.w2-opt --json-only
    scripts/analyze_cell.py L1.B1.w1-autovec.w2-opt --prompt-only   # print the LLM prompt
    MODEL=glm-4.5 scripts/analyze_cell.py L1.B1.w1-autovec.w2-opt

LLM key: read from env ZAI_API_KEY, else file .scratch/zai_api_key (gitignored).
"""
from __future__ import annotations
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "experiments", "data")
ASM_CACHE = os.path.join(ROOT, ".scratch", "asm_cache")
DEFAULT_MODEL = "glm-5.2"
ADDR = re.compile(r"^[0-9a-f]{16}$")

# Death-rate points EXCLUDED from per-cell bundles (legacy sweep values not in
# experiments/sweeps/death_rates.txt). Raw data retains them. Keep in sync with
# build_report.py.
EXCLUDE_DEATH_Q = (0.0, 0.75)


def sh(cmd):
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True).stdout


def split_cell(cell):
    layout, strat = cell.split(".", 1)
    return layout, strat


def machine_id():
    ids = [d for d in os.listdir(DATA) if os.path.isdir(os.path.join(DATA, d))]
    if len(ids) != 1:
        sys.exit(f"expected one machine under {DATA}, found {ids}; pass -M <id>")
    return ids[0]


def load_jsonl(path, cell):
    out = []
    if not os.path.exists(path):
        return out
    for line in open(path):
        try:
            r = json.loads(line)
        except Exception:
            continue
        if r.get("cell") != cell:
            continue
        if r.get("death_q") in EXCLUDE_DEATH_Q:
            continue
        out.append(r)
    return out


def source_hash(cell):
    return sh([sys.executable, os.path.join(ROOT, "scripts", "cell_hash.py"), cell]).strip()


# ---- assembly: build (cached) + disassemble step ----

def ensure_binary(cell, shash):
    layout, strat = split_cell(cell)
    cache = os.path.join(ASM_CACHE, shash)
    binp = os.path.join(cache, "bin", f"{cell}.bench")
    if os.path.exists(binp):
        return binp, cache
    os.makedirs(cache, exist_ok=True)
    cmd = ["zig", "build", "-p", cache, f"-Dlayout={layout}", f"-Dstrat={strat}",
           "-Dmode=bench", "-Doptimize=ReleaseFast"]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("build failed:\n" + (r.stderr or r.stdout)[-800:])
    return binp, cache


def step_symbol(strat):
    return f"_framework.sim.Strategy(layouts.L1.data.Data,layouts.L1.{strat}.H).step"


def disasm_step(binp, strat):
    sym = step_symbol(strat)
    nm = sh(["nm", binp])
    if sym not in nm:
        return None
    ot = sh(["otool", "-tV", binp]).splitlines()
    start = next((i + 1 for i, l in enumerate(ot)
                  if l.startswith("_") and l.rstrip().endswith(":") and sym in l), None)
    if start is None:
        return None
    body = []
    for l in ot[start:]:
        if l.startswith("_") and l.rstrip().endswith(":"):
            break
        body.append(l)
    return body


def histogram(body):
    from collections import Counter
    base = Counter()
    vector = 0
    for l in body:
        t = l.split()
        if len(t) < 2 or not ADDR.match(t[0]):
            continue
        m = t[1]
        base[m.split(".")[0]] += 1
        if "." in m and re.match(r"(2|3|4|8|16)[sdh]", m.split(".", 1)[1]):
            vector += 1
    return dict(base.most_common()), vector


# ---- godbolt source↔asm attribution (reporting-and-analysis.md §5.5/§12.4) ----
# The same ReleaseFast codegen, built strip=false + dsymutil, lets llvm-objdump
# --source attribute each asm address to its source line. llvm-objdump garbles
# the Mach-O arm64 *decode* (<unknown>), so we take ADDRESSES + SOURCE from it
# and the clean asm from otool, joined on address. Cached in bin-debug/.

OBJDUMP = ["xcrun", "llvm-objdump"]


def ensure_debug_binary(cell, shash):
    """Build the strip=false (same ReleaseFast codegen) variant + its dSYM.
    Cached at asm_cache/<shash>/bin-debug/. Returns (binp, dwarffile) or (None,None)."""
    layout, _ = split_cell(cell)
    cache = os.path.join(ASM_CACHE, shash)
    dbgprefix = os.path.join(cache, "bin-debug")
    binp = os.path.join(dbgprefix, "bin", f"{cell}.bench")
    dwarffile = os.path.join(dbgprefix, "dod.dSYM", "Contents", "Resources", "DWARF", f"{cell}.bench")
    if os.path.exists(dwarffile):
        return binp, dwarffile
    cmd = ["zig", "build", "-p", dbgprefix, f"-Dlayout={layout}", f"-Dstrat={cell.split('.',1)[1]}",
           "-Dmode=bench", "-Doptimize=ReleaseFast", "-Dkeep-debug=true"]
    if subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True).returncode != 0:
        return None, None
    subprocess.run(["dsymutil", binp, "-o", os.path.join(dbgprefix, "dod.dSYM")],
                   capture_output=True, text=True)
    return (binp, dwarffile) if os.path.exists(dwarffile) else (None, None)


def step_addr_range(binp, strat):
    """(start, stop) of the step symbol via nm. Commas in the mangled name break
    --disassemble-symbols' comma-list parsing, so callers use address ranges."""
    sym = step_symbol(strat)
    start, addrs = None, []
    for l in sh(["nm", binp]).splitlines():
        p = l.split()
        if len(p) < 2:
            continue
        if p[-1] == sym:
            start = int(p[0], 16)
        if p[1] in ("t", "T"):
            addrs.append(int(p[0], 16))
    if start is None:
        return None, None
    addrs.sort()
    return start, next((a for a in addrs if a > start), start + 0x800)


def source_map(dwarffile, start, stop):
    """{addr_int: source_line} from llvm-objdump --source. Source lines are
    ';'-comments, attributed to the addresses that follow until the next one."""
    r = subprocess.run(OBJDUMP + ["--source", f"--start-address=0x{start:x}",
                                  f"--stop-address=0x{stop:x}", dwarffile],
                       capture_output=True, text=True)
    out, cur = {}, None
    for l in r.stdout.splitlines():
        s = l.strip()
        if s.startswith(";"):
            cur = s[1:].strip() or cur
        elif (m := re.match(r"^([0-9a-f]+):", s)):
            out[int(m.group(1), 16)] = cur
    return out


def cell_source(cell, groups):
    """The cell's own source file (what the user wrote), plus a per-group map to
    the line number in that file (None for inlined library code). The SPA shows
    this real, properly-formatted source on the left and links asm blocks to
    source lines (click/hover)."""
    try:
        import cell_hash
    except ImportError:
        return None
    path = cell_hash.cell_file_path(cell)
    try:
        lines = open(path, encoding="utf-8").read().splitlines()
    except OSError:
        return None
    textline = {}
    for i, s in enumerate(lines, 1):
        key = s.strip()
        if key and key not in textline:
            textline[key] = i
    group_lines = [textline.get((g.get("source") or "").strip()) for g in groups]
    return {"file": os.path.relpath(path, ROOT), "lines": lines, "group_lines": group_lines}


def reindent_sources(cell, groups):
    """llvm-objdump mangles each source line's leading whitespace, so recover
    the real indentation: match the stripped source text to its line in the
    cell's @import closure (cell_hash walks it) and use that file line verbatim.
    Unmatched lines fall back flush-left (cleaner than llvm's mangled prefix)."""
    try:
        import cell_hash
    except ImportError:
        return groups
    closure = cell_hash.walk_closure(cell_hash.cell_file_path(cell))
    lookup = {}
    for f in closure:
        try:
            for raw in open(f, encoding="utf-8"):
                s = raw.rstrip("\n")
                key = s.strip()
                if key and key not in lookup:
                    lookup[key] = s          # the full line, real indentation intact
        except OSError:
            continue
    for g in groups:
        key = (g.get("source") or "").strip()
        g["source"] = lookup.get(key, key)  # matched: real indent; else flush-left
    return groups


def attributed_asm(cell, shash, strat, otool_body):
    """Godbolt grouping [{source, asm:[...]}]: otool gives the clean asm (by
    address), llvm-objdump --source gives each address's source line. None if
    the debug build / toolchain is unavailable (SPA falls back to flat listing)."""
    binp, dwarffile = ensure_debug_binary(cell, shash)
    if not binp:
        return None
    start, stop = step_addr_range(binp, strat)
    if start is None:
        return None
    smap = source_map(dwarffile, start, stop)
    if not smap:
        return None
    groups, cur_src, cur_asm = [], None, []
    for line in otool_body:
        t = line.split("\t")
        if len(t) < 2 or not ADDR.match(t[0]):
            continue
        src = smap.get(int(t[0], 16), cur_src)
        if src != cur_src and cur_asm:
            groups.append({"source": cur_src or "", "asm": cur_asm}); cur_asm = []
        cur_src = src
        cur_asm.append("\t".join(t[1:]).rstrip())
    if cur_asm:
        groups.append({"source": cur_src or "", "asm": cur_asm})
    return reindent_sources(cell, groups)


# ---- evidence bundle ----

def cache_transitions(bpp, hw):
    out = []
    for name, key in [("L1d", "l1dcachesize"), ("L2", "l2cachesize"), ("L3", "l3cachesize")]:
        sz = hw.get(key) or 0
        if sz:
            out.append([name, sz // bpp])
    return out


def series(runs, bpp):
    """min ns/particle per (death_q, N, threads); achieved_bw = bpp·N/ns_frame."""
    best = {}
    for r in runs:
        key = (r["death_q"], r["N"], r["threads"])
        cur = best.get(key)
        if cur is None or r["ns_particle"] < cur["ns_particle"]:
            best[key] = r
    grouped = {}
    for (q, N, T), r in sorted(best.items()):
        grouped.setdefault(q, []).append({
            "N": N, "threads": T,
            "ns_particle": round(r["ns_particle"], 3),
            "ns_frame": r["ns_frame"],
            "achieved_bw_gbs": round(bpp * N / r["ns_frame"], 2) if r["ns_frame"] else None,
        })
    return grouped


def build_evidence(cell, m, hw, runs, pmc, asm):
    bpp = runs[0]["bytes_per_particle"]
    decl = {k: runs[0][k] for k in
            ("blueprint", "ordering", "intermediates", "golden_class", "halide_expressible")}
    return {
        "cell": cell, "machine_id": m,
        "source_hash": asm["source_hash"], "git_sha": runs[0].get("git_sha"),
        "layout": runs[0]["layout"], "bytes_per_particle": bpp,
        "cell_decl": decl,
        "hardware": {k: hw[k] for k in
                     ("cpu", "l1dcachesize", "l2cachesize", "l3cachesize",
                      "cachelinesize", "streaming_bw_gbs", "logicalcpu")},
        "cache_transitions": cache_transitions(bpp, hw),
        "series": series(runs, bpp),
        "pmc": [{k: p[k] for k in ("N", "death_q", "trial", "cycles",
                 "useful_pct", "processing_pct", "delivery_pct", "discarded_pct")}
                for p in pmc],
        "asm": asm,
    }


