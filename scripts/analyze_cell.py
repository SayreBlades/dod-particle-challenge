def llm_narrate(prompt, model):
    key = read_key()
    if not key:
        sys.exit("no ZAI_API_KEY in env or .scratch/zai_api_key; use --json-only/--prompt-only")
    try:
        from zai import ZaiClient
    except ImportError:
        sys.exit("zai-sdk not installed; run `uv add zai-sdk` (or `uv sync`)")
    client = ZaiClient(api_key=key, base_url=read_base_url())
    try:
        # GLM-5.2 is a reasoning model: reasoning tokens count toward
        # max_tokens. The budget varies 2k–8k reasoning + ~5k visible, so 8000
        # is too tight at the high end (a cell can finish=length with empty
        # visible output). Default 16000 leaves headroom; override per-run.
        max_tokens = int(os.environ.get("MAX_TOKENS", "16000"))
        resp = client.chat.completions.create(
            model=model, temperature=0.3, max_tokens=max_tokens,
            messages=[{"role": "system", "content": SYSTEM},
                      {"role": "user", "content": prompt}])
        # GLM-5.2 is a reasoning model: reasoning tokens count toward max_tokens,
        # so log the split to catch truncation (finish=length means raise max_tokens).
        ch = resp.choices[0]
        u = resp.usage
        rt = getattr(getattr(u, "completion_tokens_details", None), "reasoning_tokens", None) if u else None
        print(f"  z.ai: finish={ch.finish_reason}  reasoning_tokens={rt}  "
              f"completion={getattr(u, 'completion_tokens', None)}", file=sys.stderr)
        return ch.message.content
    except Exception as e:
        # surface API errors (balance/auth/rate) with their body, not a bare traceback
        detail = getattr(getattr(e, "response", None), "text", None) or str(e)
        sys.exit(f"z.ai call failed ({model}): {detail[:500]}")


def is_layout_id(s):
    import re
    return bool(re.fullmatch(r"L\d+", s))


def read_layout_cells(layout):
    """experiments/sweeps/<layout>.cells -> full cell names, as-is
    (the file already stores 'L1.<strat>' lines; comments/blanks skipped)."""
    p = os.path.join(ROOT, "experiments", "sweeps", f"{layout}.cells")
    return [c.strip() for c in open(p)
            if c.strip() and not c.strip().startswith("#")]


def process_cell(cell, m, hw, model, json_only, prompt_only, force=False):
    layout, strat = split_cell(cell)
    runs = load_jsonl(os.path.join(DATA, m, "runs.jsonl"), cell)
    pmc = load_jsonl(os.path.join(DATA, m, "pmc.jsonl"), cell)
    if not runs:
        print(f"  no runs for {cell} — skip", file=sys.stderr)
        return "skip"
    shash = source_hash(cell)
    binp, _ = ensure_binary(cell, shash)
    body = disasm_step(binp, strat) or []
    hist, vec = histogram(body)
    asm = {"source_hash": shash, "symbol": step_symbol(strat),
           "n_instructions": len(body), "histogram": hist, "vector_insns": vec,
           "excerpt": "\n".join(body)}
    src = attributed_asm(cell, shash, strat, body)
    if src is not None:
        asm["source_attributed"] = src
        cs = cell_source(cell, src)
        if cs:
            asm["cell_source"] = cs
    evidence = build_evidence(cell, m, hw, runs, pmc, asm)
    outdir = os.path.join(ROOT, "experiments", "analysis", m, layout)
    os.makedirs(outdir, exist_ok=True)
    jpath = os.path.join(outdir, f"{strat}.json")
    mpath = os.path.join(outdir, f"{strat}.md")
    new_json = json.dumps(evidence, indent=2)
    old_json = open(jpath).read() if os.path.exists(jpath) else None
    if old_json != new_json:
        with open(jpath, "w") as f:
            f.write(new_json)
        print(f"  wrote {jpath}  ({len(body)} insn, {len(runs)} runs)", file=sys.stderr)
    else:
        print(f"  {os.path.basename(jpath)} unchanged — skip write", file=sys.stderr)
    prompt = evidence_to_prompt(evidence)
    if prompt_only:
        print(prompt)
        return "ok"
    if json_only:
        return "ok"
    if os.path.exists(mpath) and not force:
        print(f"  {os.path.basename(mpath)} exists — skip (--force to regenerate)", file=sys.stderr)
        return "skip"
    md = llm_narrate(prompt, model)
    with open(mpath, "w") as f:
        f.write(f"<!-- auto-generated by scripts/analyze_cell.py ({model}); "
                f"source_hash={shash} -->\n\n" + md.strip() + "\n")
    print(f"  wrote {mpath}", file=sys.stderr)
    return "ok"


